/* MOLMS-INVOICE-PERFORMANCE-V1
 * Invoice module responsiveness + automatic-number UX guard.
 * Safe runtime patch: does not replace accounting logic.
 */
(function(){
  'use strict';

  function pageOpen(){
    const p=document.getElementById('page-invoice');
    return !!p && p.style.display!=='none' && !p.hidden;
  }

  function numberField(){
    const p=document.getElementById('page-invoice');
    if(!p)return null;
    let el=p.querySelector('input[name="invoice_number"],input[name="invoiceNumber"],input[id*="invoice"][id*="number" i],input[id*="inv"][id*="number" i],input[id*="inv"][id*="num" i]');
    if(el)return el;
    const labels=[...p.querySelectorAll('label')].find(l=>/invoice\s*(number|reference)/i.test(l.textContent||''));
    if(labels){
      const id=labels.getAttribute('for');
      if(id)return document.getElementById(id);
      el=labels.parentElement?.querySelector('input');
      if(el)return el;
    }
    return null;
  }

  function protectNumber(){
    const el=numberField();
    if(!el)return;
    el.readOnly=true;
    el.setAttribute('aria-readonly','true');
    el.title='Automatically generated by MOLMS when the invoice is first saved.';
    el.placeholder='Auto-generated on save';
  }

  function clearNewNumber(){
    const el=numberField();
    if(!el)return;
    el.value='';
    el.readOnly=true;
    el.setAttribute('aria-readonly','true');
    el.placeholder='Auto-generated on save';
  }

  function patchNewInvoice(){
    if(typeof invNewInvoice!=='function'||invNewInvoice.__molmsPerfV1)return false;
    const base=invNewInvoice;
    invNewInvoice=function(){
      const r=base.apply(this,arguments);
      requestAnimationFrame(clearNewNumber);
      return r;
    };
    invNewInvoice.__molmsPerfV1=true;
    return true;
  }

  function patchRender(){
    if(typeof invRender!=='function'||invRender.__molmsPerfV1)return false;
    const base=invRender;
    let raf=0;
    invRender=function(){
      if(raf)return;
      const args=arguments;
      raf=requestAnimationFrame(function(){
        raf=0;
        base.apply(this,args);
      });
    };
    invRender.__molmsPerfV1=true;
    return true;
  }

  function patchSavedList(){
    if(typeof invLoadSavedList!=='function'||invLoadSavedList.__molmsPerfV1)return false;
    const base=invLoadSavedList;
    let pending=null;
    invLoadSavedList=function(){
      if(pending)return pending;
      try{
        pending=Promise.resolve(base.apply(this,arguments)).finally(()=>{pending=null});
        return pending;
      }catch(e){
        pending=null;
        throw e;
      }
    };
    invLoadSavedList.__molmsPerfV1=true;
    return true;
  }

  function boot(){
    patchNewInvoice();
    patchRender();
    patchSavedList();
    protectNumber();
    let n=0;
    const t=setInterval(()=>{
      patchNewInvoice();
      patchRender();
      patchSavedList();
      if(pageOpen())protectNumber();
      if(++n>40)clearInterval(t);
    },250);
  }

  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',boot,{once:true});
  else boot();
})();
